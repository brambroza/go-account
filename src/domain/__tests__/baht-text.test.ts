import { bahtText } from '../baht-text';

// ----------------------------------------------------------------------
// จำนวนเงินเป็นตัวอักษร — เทียบกับผลของ BAHTTEXT ใน Excel
// ----------------------------------------------------------------------

describe('bahtText', () => {
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [1, 'หนึ่งบาทถ้วน'],
    [10, 'สิบบาทถ้วน'],
    [11, 'สิบเอ็ดบาทถ้วน'],
    [20, 'ยี่สิบบาทถ้วน'],
    [21, 'ยี่สิบเอ็ดบาทถ้วน'],
    [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [110, 'หนึ่งร้อยสิบบาทถ้วน'],
    [1000, 'หนึ่งพันบาทถ้วน'],
    [1070, 'หนึ่งพันเจ็ดสิบบาทถ้วน'],
    [250000, 'สองแสนห้าหมื่นบาทถ้วน'],
    [1000000, 'หนึ่งล้านบาทถ้วน'],
    [1000001, 'หนึ่งล้านเอ็ดบาทถ้วน'],
    [2000010, 'สองล้านสิบบาทถ้วน'],
    [21000000, 'ยี่สิบเอ็ดล้านบาทถ้วน'],
    [1000000000000, 'หนึ่งล้านล้านบาทถ้วน'],
  ])('%d → %s', (amount, text) => {
    expect(bahtText(amount)).toBe(text);
  });

  it('reads satang and rounds half-up to satang first', () => {
    expect(bahtText(0.01)).toBe('หนึ่งสตางค์');
    expect(bahtText(0.5)).toBe('ห้าสิบสตางค์');
    expect(bahtText(1.25)).toBe('หนึ่งบาทยี่สิบห้าสตางค์');
    expect(bahtText(21.21)).toBe('ยี่สิบเอ็ดบาทยี่สิบเอ็ดสตางค์');
    expect(bahtText(1070.5)).toBe('หนึ่งพันเจ็ดสิบบาทห้าสิบสตางค์');
    expect(bahtText(1.005)).toBe('หนึ่งบาทหนึ่งสตางค์');
    expect(bahtText(99.999)).toBe('หนึ่งร้อยบาทถ้วน');
  });

  it('prefixes negatives with ลบ', () => {
    expect(bahtText(-1070)).toBe('ลบหนึ่งพันเจ็ดสิบบาทถ้วน');
  });
});
